# Crop the BattLab logo, scale it to fit the 480x320 screen and write it as an
# 8-bit grayscale (white-on-black) array for the boot splash.
from pathlib import Path
from PIL import Image, ImageOps
import numpy as np
root = Path(__file__).resolve().parents[1]
im = Image.open(root / 'assets/battlab_logo_source.jpg').convert('L')
a = np.array(im)
ys, xs = np.where(a > 128)
pad = 2
box = (max(xs.min() - pad, 0), max(ys.min() - pad, 0), xs.max() + 1 + pad, ys.max() + 1 + pad)
im = im.crop(box)
def scaled(W):
    H = round(im.height * W / im.width)
    s = ImageOps.autocontrast(im.resize((W, H), Image.LANCZOS), cutoff=0)
    g = np.array(s, dtype=np.uint8)
    g[g < 10] = 0          # clean JPEG noise in the black areas
    g[g > 245] = 255
    return W, H, g

def emit(prefix, W, H, g):
    flat = g.flatten()
    rows = ['  ' + ','.join(str(v) for v in flat[i:i + 24]) + ',' for i in range(0, len(flat), 24)]
    return (f'static const uint16_t {prefix}_W = {W}, {prefix}_H = {H};\n'
            f'static const uint8_t {prefix}_GRAY[] = {{\n' + '\n'.join(rows) + '\n};\n')

W, H, big = scaled(432)          # boot splash
Image.fromarray(big).save(root / 'assets/battlab_logo_preview.png')
w2, h2, small = scaled(100)      # dashboard header
Image.fromarray(small).save(root / 'assets/battlab_logo_header_preview.png')
(root / 'include/logo.h').write_text(
    '#pragma once\n#include <stdint.h>\n// Generated by tools/make_logo.py - do not edit\n' +
    emit('LOGO', W, H, big) + emit('LOGO_S', w2, h2, small))
print(W, H, w2, h2)
