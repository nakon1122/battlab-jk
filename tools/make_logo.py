# Crop the BattLab logo, scale it to fit the 480x320 screen and write it as an
# 8-bit grayscale (white-on-black) array for the boot splash.
from pathlib import Path
from PIL import Image, ImageOps
import numpy as np
root = Path(__file__).resolve().parents[1]
im = Image.open(root / 'assets/battlab_logo_source.jpg').convert('L')
a = np.array(im)
ys, xs = np.where(a > 128)
pad = 2
box = (max(xs.min() - pad, 0), max(ys.min() - pad, 0), xs.max() + 1 + pad, ys.max() + 1 + pad)
im = im.crop(box)
W = 432
H = round(im.height * W / im.width)
im = im.resize((W, H), Image.LANCZOS)
im = ImageOps.autocontrast(im, cutoff=0)
g = np.array(im, dtype=np.uint8)
g[g < 10] = 0          # clean JPEG noise in the black areas
g[g > 245] = 255
im.save(root / 'assets/battlab_logo_preview.png')
rows = []
flat = g.flatten()
for i in range(0, len(flat), 24):
    rows.append('  ' + ','.join(str(v) for v in flat[i:i + 24]) + ',')
(root / 'include/logo.h').write_text(
    '#pragma once\n#include <stdint.h>\n// Generated by tools/make_logo.py - do not edit\n'
    f'static const uint16_t LOGO_W = {W}, LOGO_H = {H};\n'
    'static const uint8_t LOGO_GRAY[] = {\n' + '\n'.join(rows) + '\n};\n')
print(W, H, len(flat))
