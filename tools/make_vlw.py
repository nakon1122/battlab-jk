# Build anti-aliased VLW fonts (LovyanGFX smooth fonts) from Inter for the Cloud Screen.
# Output: include/ui_fonts.h  (const uint8_t arrays in flash)
from pathlib import Path
import struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
INTER = '/usr/share/fonts/opentype/inter/'
ASCII = ''.join(chr(c) for c in range(0x21, 0x7F)) + '°·Δ'
DIGITS = '0123456789%.-+:'
FONTS = [  # name, file, px, charset
    ('R15', 'Inter-Regular.otf', 15, ASCII),
    ('S15', 'Inter-SemiBold.otf', 15, ASCII),
    ('S12', 'Inter-SemiBold.otf', 12, ASCII),
    ('R19', 'Inter-Regular.otf', 19, ASCII),
    ('B19', 'Inter-Bold.otf', 19, ASCII),
    ('B27', 'InterDisplay-Bold.otf', 27, ASCII),
    ('B36', 'InterDisplay-Bold.otf', 36, ASCII),
    ('B84', 'InterDisplay-Bold.otf', 84, DIGITS),
]

def vlw(path, px, chars):
    f = ImageFont.truetype(path, px)
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        x0, y0, x1, y1 = f.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        im = Image.new('L', (max(1, w), max(1, h)), 0)
        if w and h: ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
        adv = int(round(f.getlength(ch)))
        glyphs.append((ord(ch), h, w, adv, -y0, x0, im.tobytes() if w and h else b''))
    asc = -f.getbbox('d', anchor='ls')[1] if 'd' in chars else -f.getbbox('8', anchor='ls')[1]
    desc = f.getbbox('p', anchor='ls')[3] if 'p' in chars else 0
    out = struct.pack('>6i', len(glyphs), 11, px, 0, asc, desc)
    for u, h, w, adv, dy, dx, _ in glyphs: out += struct.pack('>7i', u, h, w, adv, dy, dx, 0)
    for g in glyphs: out += g[6]
    return out

lines = ['// Generated by tools/make_vlw.py from Inter (SIL Open Font License 1.1). Do not edit.', '#pragma once', '#include <stdint.h>']
total = 0
for name, fn, px, cs in FONTS:
    b = vlw(INTER + fn, px, cs); total += len(b)
    lines.append(f'static const uint8_t VLW_{name}[{len(b)}] = {{')
    for i in range(0, len(b), 32): lines.append('  ' + ','.join(str(x) for x in b[i:i+32]) + ',')
    lines.append('};')
(ROOT / 'include/ui_fonts.h').write_text('\n'.join(lines) + '\n')
print('fonts bytes', total)
