# Build an Arduino-ESP32 (2.0.x) x509 CA bundle for WiFiClientSecure::setCACertBundle
# from the Mozilla root store (/etc/ssl/certs/ca-certificates.crt).
# Format: u16 count, then per cert sorted by subject DER:
#   u16 name_len, u16 key_len, subject DER, SubjectPublicKeyInfo DER
import sys, struct
from pathlib import Path
from cryptography import x509
from cryptography.hazmat.primitives import serialization

src = Path(sys.argv[1] if len(sys.argv) > 1 else '/etc/ssl/certs/ca-certificates.crt').read_bytes()
certs = x509.load_pem_x509_certificates(src)
entries = {}
for c in certs:
    name = c.subject.public_bytes()
    key = c.public_key().public_bytes(serialization.Encoding.DER,
                                      serialization.PublicFormat.SubjectPublicKeyInfo)
    entries[name] = key  # de-duplicate by subject
items = sorted(entries.items(), key=lambda kv: kv[0])
out = bytearray(struct.pack('>H', len(items)))
for name, key in items:
    out += struct.pack('>HH', len(name), len(key)) + name + key
root = Path(__file__).resolve().parents[1]
lines = [', '.join(f'0x{b:02x}' for b in out[i:i + 20]) + ',' for i in range(0, len(out), 20)]
(root / 'include/cloud_ca_bundle.h').write_text(
    '#pragma once\n#include <stdint.h>\n'
    '// Mozilla root CA bundle for WiFiClientSecure::setCACertBundle().\n'
    '// Generated by tools/make_ca_bundle.py - do not edit.\n'
    f'// {len(items)} roots, {len(out)} bytes\n'
    'static const uint8_t CLOUD_CA_BUNDLE[] = {\n' + '\n'.join(lines) + '\n};\n')
print(len(items), 'roots,', len(out), 'bytes')
