static bool near(float a, float b) { return std::fabs(a - b) < 1e-3f; }
int main() {
  static_assert(sizeof(FRAME) == 300, "frame size");
  using namespace bmsw;
  JkSettings s;
  assert(parseJkSettings(FRAME, s) && s.valid);
  assert(near(s.v[P_UVP], 2.9f) && near(s.v[P_UVPR], 3.2f));
  assert(near(s.v[P_OVP], 4.3f) && near(s.v[P_OVPR], 4.2f));
  assert(near(s.v[P_BAL_TRIGGER], .010f) && near(s.v[P_POWER_OFF], 2.8f));
  assert(near(s.v[P_MAX_CHG], 25.f) && near(s.v[P_MAX_DSG], 150.f) && near(s.v[P_MAX_BAL], 2.f));
  assert(near(s.v[P_CHG_OTP], 70.f) && near(s.v[P_DSG_OTP], 70.f) && near(s.v[P_CHG_UTP], -20.f));
  assert(near(s.v[P_MOS_OTP], 90.f) && near(s.v[P_CAPACITY], 5.f) && near(s.v[P_BAL_START], 3.3f));
  assert(s.sw[SW_CHARGE] && s.sw[SW_DISCHARGE] && s.sw[SW_BALANCER]);
  // validation
  assert(!checkJkValue(s, P_OVP, 4.25f));
  assert(checkJkValue(s, P_OVP, 4.21f));          // too close to OVPR 4.2
  assert(checkJkValue(s, P_OVP, 4.5f));           // above safe max
  assert(checkJkValue(s, P_UVP, 3.19f));          // too close to UVPR 3.2
  assert(checkJkValue(s, P_POWER_OFF, 2.9f));     // must stay below UVP 2.9
  assert(!checkJkValue(s, P_MAX_CHG, 30.f));
  assert(!checkJkValue(s, P_CHG_UTP, -10.f));
  JkSettings none; assert(checkJkValue(none, P_OVP, 4.2f));
  // frames
  auto w = jkWriteFrame(JK_PARAMS[P_OVP].reg24, jkRaw(P_OVP, 4.25f));
  assert(w[0]==0xAA && w[4]==0x04 && w[5]==4 && w[6]==(4250&255) && w[7]==(4250>>8));
  uint8_t sum=0; for(int i=0;i<19;i++) sum+=w[i]; assert(w[19]==sum);
  auto u = jkWriteFrame(JK_PARAMS[P_CHG_UTP].reg24, jkRaw(P_CHG_UTP, -10.f));
  assert(u[6]==0x9C && u[7]==0xFF && u[8]==0xFF && u[9]==0xFF); // -100 LE
  auto a = antWriteFrame(0x0003, 0); // reference: discharge on
  assert(a[0]==0x7E && a[2]==0x51 && a[3]==0x03 && a[8]==0xAA);
  auto au = antAuthFrame(); assert(au[5]==0x0C && au[6]=='1' && au[21]==0x55);
  auto j = jbdMosFrame(true, false);   // charge on, discharge off -> 0x02
  assert(j[1]==0x5A && j[2]==0xE1 && j[5]==0x02 && j[8]==0x77);
  uint16_t c=0; for(int i=2;i<6;i++) c-=j[i]; assert(j[6]==(c>>8) && j[7]==(c&255));
  puts("params_test PASS");
}
